    private void selectMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_selectMouseClicked
    int row = selectable.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a booking!");
        return;
    }

    // Extract data from the selected row
    String bID = selectable.getValueAt(row, 0).toString();
    String rNo = selectable.getValueAt(row, 1).toString();
    String cin = selectable.getValueAt(row, 2).toString();
    String cout = selectable.getValueAt(row, 3).toString();
    String nights = selectable.getValueAt(row, 4).toString();
    String price = selectable.getValueAt(row, 5).toString();
    String tableInfo = "Booking ID: " + bID + " | Room: " + rNo;

    // Send back to payments
    payments pay = new payments(accID);
    pay.importBookingData(bID, rNo, cin, cout, nights, price, tableInfo);
    pay.setVisible(true);
    this.dispose();
      
        // TODO add your handling code here:
    }//GEN-LAST:event_selectMouseClicked

