public void displayData() {
    try {
        config conf = new config();
        
        // This query selects bookings that are 'Booked' AND do not have a record in the payments table
        String query = "SELECT b.bookings_id, b.room_id, b.check_in, b.check_out, b.total_night, b.total_price "
                     + "FROM bookings b "
                     + "LEFT JOIN payments p ON b.bookings_id = p.bookings_id "
                     + "WHERE b.account_id = '" + accID + "' "
                     + "AND b.booking_status = 'Booked' "
                     + "AND p.bookings_id IS NULL"; 

        ResultSet rs = conf.getData(query);
        
        DefaultTableModel model = (DefaultTableModel) selectable.getModel();
        String[] columnNames = {"Booking ID", "Room", "Check-In", "Check-Out", "Nights", "Price"};
        model.setColumnIdentifiers(columnNames);
        
        model.setRowCount(0);
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString(1), rs.getString(2), rs.getString(3), 
                rs.getString(4), rs.getString(5), rs.getString(6)
            });
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
    }
}

