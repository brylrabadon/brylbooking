    private void jLabel4MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel4MouseClicked
    int row = selectrooms.getSelectedRow();
    if (row != -1) {
        // Index 0 is room_id
        parent.selectedRoomId = Integer.parseInt(selectrooms.getValueAt(row, 0).toString());

        // Index 1 is type_name
        parent.ar.setText(selectrooms.getValueAt(row, 1).toString());

        // Index 5 is room_pricepernight
        parent.ppn.setText(selectrooms.getValueAt(row, 5).toString());
        
        parent.calculateTotal(); 
        this.dispose(); 
    } else {
        JOptionPane.showMessageDialog(null, "Please select a room first!");
    }

    }//GEN-LAST:event_jLabel4MouseClicked

