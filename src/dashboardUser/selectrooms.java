public void displayAvailableRooms() {
    try {
        config db = new config();
        // ADDED r.room_id to the start of the query
        String query = "SELECT r.room_id, r.room_number, r.floor, rt.type_name, r.status, r.room_pricepernight " +
                       "FROM rooms r " +
                       "JOIN room_type rt ON r.room_type_name = rt.room_type_id " +
                       "WHERE r.status = 'Available'";
        ResultSet rs = db.getData(query);
        
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) this.selectrooms.getModel();
        model.setRowCount(0); 

        while (rs.next()) {
    model.addRow(new Object[]{
        rs.getInt("room_id"),              // Index 0
        rs.getString("type_name"),          // Index 1
        rs.getString("floor"),              // Index 2
        rs.getString("room_number"),        // Index 3
        rs.getString("status"),             // Index 4
        rs.getDouble("room_pricepernight")  // Index 5 (This was causing the crash!)
    });
}
        
        // OPTIONAL: Hide the ID column so the user doesn't see it
        selectrooms.getColumnModel().getColumn(0).setMinWidth(0);
        selectrooms.getColumnModel().getColumn(0).setMaxWidth(0);
        
    } catch (SQLException e) {
        System.out.println("SQL Error: " + e.getMessage());
    }
}

