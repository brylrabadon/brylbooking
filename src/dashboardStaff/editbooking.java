    private void updatebookMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_updatebookMouseClicked
    try {
        config db = new config();
        
        // Validation: Check if dates are selected
        if(editcheckin.getDate() == null || editcheckout.getDate() == null){
            JOptionPane.showMessageDialog(this, "Please select both Check-In and Check-Out dates.");
            return;
        }

        String room_type_name = editar.getText();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String checkin = sdf.format(editcheckin.getDate());
        String checkout = sdf.format(editcheckout.getDate());
        
        // Use the public variable 'bookingID' that we defined above
        String sql = "UPDATE bookings SET room_id = ?, check_in = ?, check_out = ? WHERE bookings_id = ?";
        
        int result = db.executeUpdate(sql, room_type_name, checkin, checkout, bookingID);

        if (result > 0) {
            JOptionPane.showMessageDialog(this, "Booking updated successfully!");
            new managebookings().setVisible(true);
            this.dispose();
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Update Error: " + e.getMessage());
    }
  
    }//GEN-LAST:event_updatebookMouseClicked

