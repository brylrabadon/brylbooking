    public void calculateTotals() {
    try {
        if (editcheckin.getDate() != null && editcheckout.getDate() != null) {
            // Convert java.util.Date to LocalDate for easier calculation
            LocalDate d1 = new java.sql.Date(editcheckin.getDate().getTime()).toLocalDate();
            LocalDate d2 = new java.sql.Date(editcheckout.getDate().getTime()).toLocalDate();

            // Calculate the difference in days
            long nights = ChronoUnit.DAYS.between(d1, d2);

            if (nights > 0) {
                editn.setText(String.valueOf(nights));
                
                // Assuming 500.00 is your per-night rate
                double rate = 500.00; 
                double total = nights * rate;
                
                edittc.setText(String.format("%.2f", total));
            } else {
                // If check-out is before or same as check-in
                editn.setText("0");
                edittc.setText("0.00");
            }
        }
    } catch (Exception e) {
        // Silently fail or log if dates are in middle of being updated
        System.out.println("Calc Error: " + e.getMessage());
    }
}

    
    

